// Builds a test copy of the app that cannot be mistaken for the real one.
//
//   npm run preview
//
// Why this exists: the version on the branch is the version meant for
// referees, so it must not carry test branding — bake a blue icon into the
// sources and merging the branch would put a blue icon on everybody's phone.
// So the test build is *generated* instead. One source of truth, and the thing
// that differs is a build output nobody merges.
//
// What it changes, and nothing else:
//
//   the icons        the kite inside the logo in blue, not the SBA's gold
//   the name         "SBA NEXT", which fits in the ~11 characters iOS shows
//   the cache name   its own, so it can never collide with the real app's
//   a marker         TEST next to the version, inside the app
//
// The code is copied byte for byte. A test build that differs from the branch
// in any way that matters would be worse than no test build at all.

import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { recolourLogo } from './recolour-logo.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const OUT = join(ROOT, 'preview');

/** The hue the logo's gold kite is rotated to. 217 is a plain blue. */
const BLUE_HUE = Number(process.env['PREVIEW_HUE'] ?? 217);

const version = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version;

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

// The app, exactly as it is on the branch.
for (const file of ['index.html', 'solo.js', 'sw.js', 'manifest.webmanifest', 'qr.svg']) {
  cpSync(join(ROOT, file), join(OUT, file));
}
cpSync(join(ROOT, 'app'), join(OUT, 'app'), { recursive: true });

// The same hawk with a blue kite instead of the SBA's gold. The bird, the eye
// and the white ground stay exactly as they are — it is the logo that differs,
// not a colour put behind it.
const blueLogo = join(OUT, 'logo.png');
await recolourLogo(blueLogo, BLUE_HUE);

execFileSync('node', [join(ROOT, 'tools/make-icons.mjs')], {
  cwd: ROOT,
  env: { ...process.env, ICON_LOGO: blueLogo },
  stdio: 'inherit',
});
for (const size of [180, 192, 512]) {
  cpSync(join(ROOT, `icon-${size}.png`), join(OUT, `icon-${size}.png`));
}
// Put the real icons back, so a test build never leaves the branch changed.
execFileSync('node', [join(ROOT, 'tools/make-icons.mjs')], { cwd: ROOT, stdio: 'inherit' });

const edit = (file, changes) => {
  const path = join(OUT, file);
  let text = readFileSync(path, 'utf8');
  for (const [from, to] of changes) {
    if (!text.includes(from)) throw new Error(`${file}: could not find ${JSON.stringify(from)}`);
    text = text.replaceAll(from, to);
  }
  writeFileSync(path, text);
};

// A name that says what it is, short enough for iOS not to truncate it away.
edit('manifest.webmanifest', [
  ['"SBA Replay Lite"', '"SBA Replay NEXT (test)"'],
  ['"SBA Replay"', '"SBA NEXT"'],
]);

// Its own cache, so it cannot collide with the real app's under any
// circumstances, whatever path it ends up served from.
//
// And — this one matters far more than it looks — its cleanup is narrowed to
// its own caches. Caches are per *origin*, not per scope, so the real app and
// a test build served from the same github.io host share one cache store. The
// stock `activate` deletes every cache that is not its own, which means simply
// opening the test build would delete the real app's offline cache, and the
// next time a referee opened the real app in a hall with no signal it would
// not open at all. The one failure this whole app exists to avoid.
edit('sw.js', [
  ["const CACHE = 'vrl-v3';", `const CACHE = 'vrl-next-${version}';`],
  [
    '.then((names) => Promise.all(names.filter((name) => name !== CACHE).map((name) => caches.delete(name))))',
    '.then((names) =>\n        Promise.all(\n          names\n            // Only ever this test build\'s own. See tools/make-preview.mjs.\n            .filter((name) => name.startsWith(\'vrl-next-\') && name !== CACHE)\n            .map((name) => caches.delete(name))\n        )\n      )',
  ],
]);

// And a marker inside the app, so the version on the idle screen says which
// build it is without anybody having to remember.
edit('solo.js', [["el('version').textContent = VERSION;", "el('version').textContent = `${VERSION} TEST`;"]]);

writeFileSync(
  join(OUT, 'README.md'),
  `# Not the app\n\nA test build of SBA Replay Lite ${version}, generated by \`npm run preview\`.\n` +
    `Blue icon, "SBA NEXT" on the home screen, its own offline cache.\n\n` +
    `The app referees use is at https://martinfrancu.github.io/VRL/ and is unaffected by this.\n`
);

console.log(`\n  preview of ${version} written to preview/`);
